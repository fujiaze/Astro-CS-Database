def generate(root: Path, check_only: bool) -> list[Path]:
    from . import bindings
    from .model_ast import DeclarationModel, dump_ast

    model = DeclarationModel(dump_ast(root / "include/acsd/model.hpp",
                                      "clang++",
                                      root / "build/typed-bindings"))
    metadata, _dependencies = bindings.load_process_metadata()
    specs = derive_specs(model)

    # Coverage: the generated operation set must equal the whitelist exactly.
    expected = {process.process_id: list(process.operations)
                for process in metadata}
    generated: dict[str, list[str]] = {}
    for spec in specs:
        generated.setdefault(spec.process, []).append(spec.operation)
    if set(expected) != set(generated):
        raise SystemExit(f"generated processes {sorted(generated)} differ from "
                         f"the whitelist {sorted(expected)}")
    for process_id, operations in expected.items():
        if sorted(operations) != sorted(generated[process_id]):
            raise SystemExit(
                f"{process_id}: generated operations "
                f"{sorted(generated[process_id])} differ from the whitelist "
                f"{sorted(operations)}")
    if len(specs) != 57 or len(metadata) != 22:
        raise SystemExit(f"coverage mismatch: {len(metadata)} processes / "
                         f"{len(specs)} operations")

    registry = CodecRegistry(model)
    for spec in specs:
        registry.require_input(spec.struct, spec.input_cpp, spec.fields)
        registry.require(spec.output)

    files: dict[Path, str] = {
        root / "include/acsd/modules/generated/inputs.hpp":
            emit_inputs_header(specs),
        root / "include/acsd/modules/generated/codecs.hpp":
            emit_codecs_header(specs),
        root / "include/acsd/modules/generated/status.hpp":
            emit_status_header(),
        root / "src/runtime/generated/generated_hooks.hpp":
            emit_hooks_header(metadata, registry),
        root / "src/runtime/generated/codecs.cpp":
            emit_codecs_cpp(specs, registry, model),
        root / "src/runtime/generated/typed_operations.cpp":
            emit_typed_operations(specs, metadata, registry),
        root / "src/runtime/generated/builtin_processes.cpp":
            emit_builtin_processes(metadata),
        root / "src/runtime/generated/status.cpp":
            emit_status_cpp(specs, metadata, registry),
    }

    changed: list[Path] = []
    for path, content in files.items():
        if not content.endswith("\n"):
            content += "\n"
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        changed.append(path)
        if not check_only:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    return changed
