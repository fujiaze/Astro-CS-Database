PRIMITIVE_CPP = {
    "bool": "bool", "f64": "double", "u8": "std::uint8_t",
    "u16": "std::uint16_t", "u32": "U32", "u64": "U64",
    "i32": "std::int32_t", "i64": "std::int64_t",
    "string": "std::string", "id": "Id",
}

PRIMITIVE_DECODE = {
    "bool": "codec::decode_bool", "f64": "codec::decode_double",
    "u8": "codec::decode_u8", "u16": "codec::decode_u16",
    "u32": "codec::decode_u32", "u64": "codec::decode_u64",
    "i32": "codec::decode_i32", "i64": "codec::decode_i64",
    "string": "codec::decode_string", "id": "codec::decode_id",
}

ENUM_SCHEMA_KIND = "string"


def cpp_type(type_: Type) -> str:
    if type_.kind in PRIMITIVE_CPP:
        return PRIMITIVE_CPP[type_.kind]
    if type_.kind == "named":
        return type_.name
    if type_.kind == "enum":
        return type_.name
    if type_.kind == "ref":
        pointee = type_.args[0]
        if pointee.kind == "named" and pointee.name == "Array":
            return "ArrayRef"
        return f"Ref<{cpp_type(pointee)}>"
    if type_.kind == "vector":
        return f"std::vector<{cpp_type(type_.args[0])}>"
    if type_.kind == "array":
        return f"std::array<{cpp_type(type_.args[0])}, {type_.count}>"
    if type_.kind == "optional":
        return f"std::optional<{cpp_type(type_.args[0])}>"
    if type_.kind == "variant":
        return "std::variant<" + ", ".join(cpp_type(a) for a in type_.args) + ">"
    raise SystemExit(f"no C++ spelling for {type_.describe()}")


def mangle(type_: Type) -> str:
    if type_.kind in PRIMITIVE_CPP:
        return type_.kind
    if type_.kind in ("named", "enum"):
        return type_.name.replace("::", "_")
    if type_.kind == "ref":
        return "ref_" + mangle(type_.args[0])
    if type_.kind == "vector":
        return "vector_" + mangle(type_.args[0])
    if type_.kind == "array":
        return f"array_{mangle(type_.args[0])}_{type_.count}"
    if type_.kind == "optional":
        return "optional_" + mangle(type_.args[0])
    if type_.kind == "variant":
        return "variant_" + "_".join(mangle(a) for a in type_.args)
    raise SystemExit(f"no mangled name for {type_.describe()}")


def shared_key(type_: Type) -> tuple[str, str] | None:
    if type_.kind == "named" and ("named", type_.name) in SHARED_VALUES:
        return ("named", type_.name)
    if type_.kind == "vector" and len(type_.args) == 1 and \
            type_.args[0].kind == "named":
        key = "vector:" + type_.args[0].name
        if key in SHARED_CONTAINERS:
            return ("container", key)
    return None


def schema_for(type_: Type, model: DeclarationModel) -> dict:
    """A structural JSON schema for one wire value."""
    if type_.kind == "bool":
        return {"type": "boolean"}
    if type_.kind in ("u8", "u16", "u32", "u64", "i32", "i64"):
        return {"type": "integer"}
    if type_.kind == "f64":
        return {"oneOf": [
            {"type": "number"},
            {"type": "object", "required": ["f64"],
             "properties": {"f64": {"type": "string",
                                    "pattern": "^[0-9a-f]{16}$"}},
             "additionalProperties": False},
        ]}
    if type_.kind == "string":
        return {"type": "string"}
    if type_.kind == "id":
        return {"type": "string", "minLength": 1}
    shared = shared_key(type_)
    if shared is not None:
        return shared_schema(shared, model)
    if type_.kind == "enum":
        return {"type": "string",
                "enum": model.enum_constants(type_.name)}
    if type_.kind == "ref":
        pointee = type_.args[0]
        return {
            "type": "object", "additionalProperties": False,
            "required": ["$ref"],
            "properties": {"$ref": {"type": "string", "minLength": 1}},
            "x-acsd-object": cpp_type(pointee),
        }
    if type_.kind == "vector":
        return {"type": "array", "items": schema_for(type_.args[0], model)}
    if type_.kind == "array":
        inner = schema_for(type_.args[0], model)
        return {"type": "array", "items": inner,
                "minItems": type_.count, "maxItems": type_.count}
    if type_.kind == "optional":
        return {"oneOf": [schema_for(type_.args[0], model),
                          {"type": "null"}]}
    if type_.kind == "variant":
        return {"oneOf": [schema_for(alternative, model)
                          for alternative in type_.args]}
    if type_.kind == "named":
        if type_.name == "HeaderField":
            raise SystemExit("HeaderField must be reached through HeaderFields")
        record = model.record(type_.name)
        properties: dict[str, dict] = {}
        required: list[str] = []
        for field in all_fields(record, model):
            optional = field.type.kind == "optional"
            properties[field.name] = schema_for(field.type, model)
            if not optional:
                required.append(field.name)
        return {"type": "object", "required": required,
                "properties": properties, "additionalProperties": False}
    raise SystemExit(f"no schema for {type_.describe()}")


