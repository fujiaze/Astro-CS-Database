"""C++ emitter for the typed Input structs, TypeIds, schemas and codecs.

Everything emitted here is derived from the declaration model in
include/acsd/model.hpp plus the operation/process tables in bindings.py.  The
output is a deterministic, reviewable set of files:

  include/acsd/modules/generated/inputs.hpp     typed Input structs
  include/acsd/modules/generated/codecs.hpp     type_codec<T> specialisations
  include/acsd/modules/generated/status.hpp     coverage/bounds/run status
  src/runtime/generated/codecs.cpp              schema + decode/encode + types
  src/runtime/generated/typed_operations.cpp    57 Operation hook sets
  src/runtime/generated/builtin_processes.cpp   22 ProcessDescriptors
  src/runtime/generated/status.cpp              generated status/report data

No scientific algorithm is emitted.  The run hooks are named unsupported for
M0 (the M4/M5 integration supplies the real module implementation), and every
refusal carries its reason in an Issue.
"""
