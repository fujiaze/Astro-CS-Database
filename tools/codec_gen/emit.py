CONTAINER_KINDS = ("vector", "array", "optional", "variant")


class CodecRegistry:
    """All wire codec functions reachable from the 57 Inputs and their Outputs."""

    def __init__(self, model: DeclarationModel):
        self.model = model
        self.types: dict[str, Type] = {}
        self.order: list[str] = []
        # struct name -> (qualified C++ type, derived Input fields)
        self.inputs: dict[str, tuple[str, list[InputField]]] = {}

    # -- collection -------------------------------------------------------

    def require(self, type_: Type) -> None:
        if type_.kind in PRIMITIVE_CPP:
            return
        if type_.kind in ("named", "enum", "ref") or type_.kind in CONTAINER_KINDS:
            name = mangle(type_)
            if name in self.types:
                return
            self.types[name] = type_
            self.order.append(name)
            if shared_key(type_) is not None:
                return
            for child in self._children(type_):
                self.require(child)
            return
        raise SystemExit(f"cannot generate a codec for {type_.describe()}")

    def _children(self, type_: Type) -> list[Type]:
        if type_.kind == "named":
            record = self.model.record(type_.name)
            if record.has_virtual:
                raise SystemExit(
                    f"{type_.name} is polymorphic and cannot be a by-value "
                    f"wire field; use Ref<{type_.name}>")
            return [field.type for field in all_fields(record, self.model)]
        if type_.kind in ("vector", "array", "optional"):
            return [type_.args[0]]
        if type_.kind == "variant":
            return list(type_.args)
        return []

    # -- expressions ------------------------------------------------------

    def decode_expr(self, type_: Type, source: str) -> str:
        if type_.kind in PRIMITIVE_CPP:
            return f"{PRIMITIVE_DECODE[type_.kind]}({source}, origin)"
        return f"wire_decode__{mangle(type_)}({source}, origin, objects)"

    def encode_expr(self, type_: Type, source: str) -> str:
        if type_.kind in PRIMITIVE_CPP:
            if type_.kind == "f64":
                return (f"codec::ok<json>(codec::encode_double({source}))")
            if type_.kind in ("u8", "u16"):
                return (f"codec::ok<json>(json(static_cast<std::uint64_t>("
                        f"{source})))")
            return f"codec::ok<json>(json({source}))"
        return f"wire_encode__{mangle(type_)}({source}, origin, objects)"

    # -- prototypes -------------------------------------------------------

    def require_input(self, struct: str, cpp: str,
                      fields: list[InputField]) -> None:
        self.inputs[struct] = (cpp, fields)
        for field in fields:
            self.require(field.type)

    def prototypes(self) -> str:
        lines = []
        for struct, (cpp, fields) in self.inputs.items():
            lines.append(
                f"Result<{cpp}> wire_decode__input_{struct}(const json& node, "
                f"std::string_view origin, rt::WireObjects& objects);")
            lines.append(
                f"Result<json> wire_encode__input_{struct}(const {cpp}& value, "
                f"std::string_view origin, rt::WireObjects& objects);")
        for name in self.order:
            type_ = self.types[name]
            cpp = cpp_type(type_)
            lines.append(
                f"Result<{cpp}> wire_decode__{name}(const json& node, "
                f"std::string_view origin, rt::WireObjects& objects);")
            lines.append(
                f"Result<json> wire_encode__{name}(const {cpp}& value, "
                f"std::string_view origin, rt::WireObjects& objects);")
        return "\n".join(lines)

    # -- definitions ------------------------------------------------------

    def definitions(self) -> str:
        blocks = [self._input_definition(struct, cpp, fields)
                  for struct, (cpp, fields) in self.inputs.items()]
        blocks.extend(self._definition(name) for name in self.order)
        return "\n\n".join(blocks)

    def _input_definition(self, struct: str, cpp: str,
                          fields: list[InputField]) -> str:
        names = ", ".join(f'"{field.name}"' for field in fields)
        decode_body = []
        encode_body = []
        for field in fields:
            decode_body.append(f"""  {{
    auto member = codec::require_member(node, "{field.name}", origin);
    if (member.code != Code::ok) return codec::remap<{cpp}>(member);
    auto decoded = {self.decode_expr(field.type, "**member.value")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    value.{field.name} = std::move(*decoded.value);
  }}""")
            encode_body.append(f"""  {{
    auto encoded = {self.encode_expr(field.type, f"value.{field.name}")};
    if (encoded.code != Code::ok) return codec::remap<json>(encoded);
    node["{field.name}"] = std::move(*encoded.value);
  }}""")
        decode_text = "\n".join(decode_body)
        encode_text = "\n".join(encode_body)
        return f"""Result<{cpp}> wire_decode__input_{struct}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  if (!node.is_object()) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON object");
  }}
  auto known = codec::reject_unknown(node, {{{names}}}, origin);
  if (known.code != Code::ok) return codec::remap<{cpp}>(known);
  {cpp} value{{}};
{decode_text}
  return codec::ok<{cpp}>(std::move(value));
}}

Result<json> wire_encode__input_{struct}(const {cpp}& value,
    std::string_view origin, rt::WireObjects& objects) {{
  json node = json::object();
{encode_text}
  return codec::ok<json>(std::move(node));
}}"""

    def _definition(self, name: str) -> str:
        type_ = self.types[name]
        cpp = cpp_type(type_)
        shared = shared_key(type_)
        if shared is not None:
            return self._shared_definition(name, type_, cpp, shared)
        if type_.kind == "ref":
            pointee = cpp_type(type_.args[0])
            return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  return codec::decode_ref<{pointee}>(objects, node, origin);
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  return codec::encode_ref<{pointee}>(objects, value, origin);
}}"""
        if type_.kind == "enum":
            return self._enum_definition(name, type_)
        if type_.kind == "named":
            return self._struct_definition(name, type_)
        if type_.kind == "vector":
            return self._vector_definition(name, type_)
        if type_.kind == "array":
            return self._array_definition(name, type_)
        if type_.kind == "optional":
            return self._optional_definition(name, type_)
        if type_.kind == "variant":
            return self._variant_definition(name, type_)
        raise SystemExit(f"no definition for {type_.describe()}")

    def _shared_definition(self, name, type_, cpp, shared) -> str:
        if shared[0] == "container":
            decode_fn, encode_fn = SHARED_CONTAINERS[shared[1]]
            shape_check = (
                f"""  if (!node.is_array()) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON array");
  }}""")
        else:
            decode_fn, encode_fn = SHARED_VALUES[shared]
            shape_check = (
                f"""  if (!node.is_object()) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON object");
  }}""")
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  (void)objects;
{shape_check}
  return codec::ok<{cpp}>(codec::{decode_fn}(node));
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  (void)objects;
  (void)origin;
  return codec::ok<json>(codec::{encode_fn}(value));
}}"""

    def _enum_definition(self, name, type_) -> str:
        cpp = cpp_type(type_)
        constants = self.model.enum_constants(type_.name)
        decode_checks = "\n".join(
            f'    if (name == "{constant}") return codec::ok<{cpp}>({cpp}::'
            f'{constant});' for constant in constants)
        encode_cases = "\n".join(
            f'    case {cpp}::{constant}: return codec::ok<json>(json('
            f'"{constant}"));' for constant in constants)
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  (void)objects;
  if (node.is_string()) {{
    const std::string name = node.get<std::string>();
{decode_checks}
  }}
  return codec::failure<{cpp}>(Code::invalid_request, origin,
                               "unknown {type_.name} enumerator");
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  (void)objects;
  (void)origin;
  switch (value) {{
{encode_cases}
  }}
  return codec::failure<json>(Code::invalid_request, origin,
                              "invalid {type_.name} value");
}}"""

    def _struct_definition(self, name, type_) -> str:
        record = self.model.record(type_.name)
        fields = all_fields(record, self.model)
        cpp = cpp_type(type_)
        field_names = ", ".join(f'"{field.name}"' for field in fields)
        decode_body: list[str] = []
        encode_body: list[str] = []
        for field in fields:
            source = f"(*member.value)"
            if field.type.kind == "optional":
                decode_body.append(f"""  if (const json* member = codec::member(node, "{field.name}")) {{
    auto decoded = {self.decode_expr(field.type.args[0], "*member")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    value.{field.name} = std::move(*decoded.value);
  }}""")
                encode_body.append(f"""  if (value.{field.name}.has_value()) {{
    auto encoded = {self.encode_expr(field.type.args[0],
                                     f"*value.{field.name}")};
    if (encoded.code != Code::ok) return codec::remap<json>(encoded);
    node["{field.name}"] = std::move(*encoded.value);
  }} else {{
    node["{field.name}"] = nullptr;
  }}""")
            else:
                decode_body.append(f"""  {{
    auto member = codec::require_member(node, "{field.name}", origin);
    if (member.code != Code::ok) return codec::remap<{cpp}>(member);
    auto decoded = {self.decode_expr(field.type, "**member.value")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    value.{field.name} = std::move(*decoded.value);
  }}""")
                encode_body.append(f"""  {{
    auto encoded = {self.encode_expr(field.type, f"value.{field.name}")};
    if (encoded.code != Code::ok) return codec::remap<json>(encoded);
    node["{field.name}"] = std::move(*encoded.value);
  }}""")
        decode_text = "\n".join(decode_body)
        encode_text = "\n".join(encode_body)
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  if (!node.is_object()) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON object");
  }}
  auto known = codec::reject_unknown(node, {{{field_names}}}, origin);
  if (known.code != Code::ok) return codec::remap<{cpp}>(known);
  {cpp} value{{}};
{decode_text}
  return codec::ok<{cpp}>(std::move(value));
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  json node = json::object();
{encode_text}
  return codec::ok<json>(std::move(node));
}}"""

    def _vector_definition(self, name, type_) -> str:
        cpp = cpp_type(type_)
        element = type_.args[0]
        element_cpp = cpp_type(element)
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  if (!node.is_array()) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON array");
  }}
  {cpp} values;
  values.reserve(node.size());
  for (const json& item : node) {{
    auto decoded = {self.decode_expr(element, "item")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    values.push_back(std::move(*decoded.value));
  }}
  return codec::ok<{cpp}>(std::move(values));
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  json node = json::array();
  for (const auto& item : value) {{
    auto encoded = {self.encode_expr(element, "item")};
    if (encoded.code != Code::ok) return codec::remap<json>(encoded);
    node.push_back(std::move(*encoded.value));
  }}
  return codec::ok<json>(std::move(node));
}}"""

    def _array_definition(self, name, type_) -> str:
        cpp = cpp_type(type_)
        element = type_.args[0]
        count = type_.count
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  if (!node.is_array() || node.size() != {count}) {{
    return codec::failure<{cpp}>(Code::invalid_request, origin,
                                 "expected a JSON array of exactly {count} "
                                 "elements");
  }}
  {cpp} values{{}};
  for (std::size_t index = 0; index < {count}; ++index) {{
    auto decoded = {self.decode_expr(element, "node[index]")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    values[index] = std::move(*decoded.value);
  }}
  return codec::ok<{cpp}>(std::move(values));
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  json node = json::array();
  for (const auto& item : value) {{
    auto encoded = {self.encode_expr(element, "item")};
    if (encoded.code != Code::ok) return codec::remap<json>(encoded);
    node.push_back(std::move(*encoded.value));
  }}
  return codec::ok<json>(std::move(node));
}}"""

    def _optional_definition(self, name, type_) -> str:
        cpp = cpp_type(type_)
        inner = type_.args[0]
        inner_cpp = cpp_type(inner)
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
  if (node.is_null()) return codec::ok<{cpp}>({cpp}{{}});
  auto decoded = {self.decode_expr(inner, "node")};
  if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
  {cpp} value;
  value = std::move(*decoded.value);
  return codec::ok<{cpp}>(std::move(value));
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
  if (!value.has_value()) return codec::ok<json>(json(nullptr));
  return {self.encode_expr(inner, "*value")};
}}"""

    def _variant_definition(self, name, type_) -> str:
        cpp = cpp_type(type_)
        alternatives = list(type_.args)
        decode_parts: list[str] = []
        for alternative in alternatives:
            if alternative.kind == "string":
                condition = "node.is_string()"
            elif alternative.kind in ("u8", "u16", "u32", "u64", "i32", "i64"):
                condition = "node.is_number_integer()"
            elif alternative.kind == "f64":
                condition = "node.is_number()"
            elif alternative.kind == "bool":
                condition = "node.is_boolean()"
            else:
                raise SystemExit(
                    f"variant alternative {alternative.describe()} is not a "
                    f"scalar; extend the generator explicitly")
            decode_parts.append(f"""  if ({condition}) {{
    auto decoded = {self.decode_expr(alternative, "node")};
    if (decoded.code != Code::ok) return codec::remap<{cpp}>(decoded);
    {cpp} value{{std::move(*decoded.value)}};
    return codec::ok<{cpp}>(std::move(value));
  }}""")
        encode_parts: list[str] = []
        for alternative in alternatives:
            alternative_cpp = cpp_type(alternative)
            encode_parts.append(f"""  if (std::holds_alternative<{alternative_cpp}>(value)) {{
    return {self.encode_expr(alternative,
                             f"std::get<{alternative_cpp}>(value)")};
  }}""")
        decode_text = "\n".join(decode_parts)
        encode_text = "\n".join(encode_parts)
        return f"""Result<{cpp}> wire_decode__{name}(const json& node,
    std::string_view origin, rt::WireObjects& objects) {{
{decode_text}
  return codec::failure<{cpp}>(Code::invalid_request, origin,
                               "no variant alternative matches the JSON value");
}}

Result<json> wire_encode__{name}(const {cpp}& value, std::string_view origin,
    rt::WireObjects& objects) {{
{encode_text}
  return codec::failure<json>(Code::invalid_request, origin,
                              "the variant holds an unsupported alternative");
}}"""


