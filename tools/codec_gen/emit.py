class UnitChecks:
    def __init__(self, registry: "CodecRegistry"):
        self.registry = registry
        self.cache: dict[str, bool] = {}

    def needed(self, type_: Type) -> bool:
        name = mangle(type_) if type_.kind not in PRIMITIVE_CPP else ""
        if name in self.cache:
            return self.cache[name]
        result = self._needed(type_)
        if name:
            self.cache[name] = result
        return result

    def _needed(self, type_: Type) -> bool:
        if type_.kind == "named":
            if type_.name == "Unit":
                return True
            record = self.registry.model.record(type_.name)
            return any(self.needed(field.type)
                       for field in all_fields(record, self.registry.model))
        if type_.kind in ("vector", "array", "optional"):
            return self.needed(type_.args[0])
        if type_.kind == "variant":
            return any(self.needed(argument) for argument in type_.args)
        return False

    def prototypes(self) -> str:
        lines = []
        for name in self.registry.order:
            type_ = self.registry.types[name]
            if not self.needed(type_):
                continue
            lines.append(
                f"Result<Done> wire_check_units__{name}(const "
                f"{cpp_type(type_)}& value, std::string_view origin, "
                f"std::string_view path);")
        for struct, (cpp, fields) in self.registry.inputs.items():
            if not any(self.needed(field.type) for field in fields):
                continue
            lines.append(
                f"Result<Done> wire_check_units__input_{struct}(const {cpp}& "
                f"value, std::string_view origin, std::string_view path);")
        return "\n".join(lines)

    def definitions(self) -> str:
        blocks = []
        for name in self.registry.order:
            type_ = self.registry.types[name]
            if not self.needed(type_):
                continue
            blocks.append(self._definition(name, type_))
        for struct, (cpp, fields) in self.registry.inputs.items():
            if not any(self.needed(field.type) for field in fields):
                continue
            blocks.append(self._input_definition(struct, cpp, fields))
        return "\n\n".join(blocks)

    def _definition(self, name: str, type_: Type) -> str:
        cpp = cpp_type(type_)
        return f"""Result<Done> wire_check_units__{name}(const {cpp}& value,
    std::string_view origin, std::string_view path) {{
{self._body(type_, "value")}
  return codec::ok<Done>(Done{{}});
}}"""

    def _body(self, type_: Type, source: str) -> str:
        if type_.kind == "named":
            if type_.name == "Unit":
                return f"""  (void)path;
  if ({source}.scale.empty()) {{
    return codec::failure<Done>(Code::invalid_request, origin,
                                "a Unit carries no named scale");
  }}
  if (!std::isfinite({source}.multiplier)) {{
    return codec::failure<Done>(Code::invalid_request, origin,
                                "a Unit multiplier is not finite");
  }}"""
            record = self.registry.model.record(type_.name)
            lines = []
            for field in all_fields(record, self.registry.model):
                lines.append(self._body(field.type,
                                        f"{source}.{field.name}"))
            return "\n".join(line for line in lines if line)
        if type_.kind in ("vector", "array"):
            inner = type_.args[0]
            if not self.needed(inner):
                return ""
            return f"""  for (std::size_t unit_index = 0; unit_index < {source}.size();
       ++unit_index) {{
    auto checked = wire_check_units__{mangle(inner)}({source}[unit_index],
                                                         origin, path);
    if (checked.code != Code::ok) return checked;
  }}"""
        if type_.kind == "optional":
            inner = type_.args[0]
            if not self.needed(inner):
                return ""
            return f"""  if ({source}.has_value()) {{
    auto checked = wire_check_units__{mangle(inner)}(*{source}, origin, path);
    if (checked.code != Code::ok) return checked;
  }}"""
        if type_.kind == "variant":
            return ""
        if type_.kind == "ref":
            return ""
        return ""

    def _input_definition(self, struct: str, cpp: str,
                          fields: list[InputField]) -> str:
        lines = []
        for field in fields:
            if self.needed(field.type):
                lines.append(self._body(field.type, f"value.{field.name}"))
        body = "\n".join(line for line in lines if line)
        return f"""Result<Done> wire_check_units__input_{struct}(const {cpp}& value,
    std::string_view origin, std::string_view path) {{
  (void)path;
{body}
  return codec::ok<Done>(Done{{}});
}}"""


