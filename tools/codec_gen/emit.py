def all_fields(record: Record, model: DeclarationModel) -> list:
    fields = []
    for base in record.bases:
        base_type = model.parse(base.strip(), None)
        if base_type.kind != "named":
            raise SystemExit(
                f"{record.qualified} has a non-wireable base '{base}'")
        fields.extend(all_fields(model.record(base_type.name), model))
    fields.extend(record.fields)
    return fields


