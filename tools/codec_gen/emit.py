def _unit_wrappers(registry: "CodecRegistry") -> str:
    checks = UnitChecks(registry)
    blocks = []
    for struct, (cpp, fields) in registry.inputs.items():
        if not any(checks.needed(field.type) for field in fields):
            continue
        blocks.append(f"""namespace detail {{
Result<Done> check_input_units_{struct}(const {cpp}& value,
                                       std::string_view origin) {{
  return wire_check_units__input_{struct}(value, origin, "");
}}
}}  // namespace detail""")
    return "\n\n".join(blocks)


def _codec_wrappers(specs: list[OpSpec], registry: "CodecRegistry",
                    outputs: list[Type]) -> str:
    blocks = []
    targets = [("input_" + struct, cpp)
               for struct, (cpp, _fields) in registry.inputs.items()]
    targets.extend((mangle(type_), cpp_type(type_)) for type_ in outputs)
    for name, cpp in targets:
        blocks.append(f"""Result<{cpp}> codec_decode__{name}(
    rt::InvocationContext ctx, std::string_view text,
    rt::WireObjects& objects) {{
  (void)ctx;
  constexpr std::string_view origin = "wire.decode.{name}";
  auto parsed = codec::parse_json_object(text, origin);
  if (parsed.code != Code::ok) return codec::remap<{cpp}>(parsed);
  return wire_decode__{name}(*parsed.value, origin, objects);
}}

Result<std::string> codec_encode__{name}(
    rt::InvocationContext ctx, const {cpp}& value,
    rt::WireObjects& objects) {{
  (void)ctx;
  constexpr std::string_view origin = "wire.encode.{name}";
  auto encoded = wire_encode__{name}(value, origin, objects);
  if (encoded.code != Code::ok) return codec::remap<std::string>(encoded);
  return codec::ok<std::string>(encoded.value->dump());
}}""")
    return "\n\n".join(blocks)


def _json_schema_text_for(spec: OpSpec) -> str:
    return pyjson.dumps(_input_schema(spec), separators=(",", ":"))


def _validation_checks(spec: OpSpec) -> list[str]:
    checks: list[str] = []
    for field in spec.fields:
        access = f"input->{field.name}"
        if field.type.kind == "ref":
            checks.append(
                f"  if (!{access}) {{\n"
                f"    return invalid<rt::Done>(origin,\n"
                f"        \"field '{field.name}' is a required object "
                f"reference but is null\");\n"
                f"  }}")
        elif field.type.kind == "id":
            checks.append(
                f"  if ({access}.empty()) {{\n"
                f"    return invalid<rt::Done>(origin,\n"
                f"        \"field '{field.name}' is a required Id but is "
                f"empty\");\n"
                f"  }}")
        elif field.type.kind == "f64":
            checks.append(
                f"  if (!std::isfinite({access})) {{\n"
                f"    return invalid<rt::Done>(origin,\n"
                f"        \"field '{field.name}' is not a finite double\");\n"
                f"  }}")
        elif field.type.kind == "enum":
            constants = _SCHEMA_MODEL[0].enum_constants(field.type.name)
            condition = " || ".join(
                f"{access} == {field.type.name}::{constant}"
                for constant in constants)
            checks.append(
                f"  if (!({condition})) {{\n"
                f"    return invalid<rt::Done>(origin,\n"
                f"        \"field '{field.name}' is not a declared "
                f"{field.type.name} enumerator\");\n"
                f"  }}")
    return checks


