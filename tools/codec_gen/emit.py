@dataclass
class OpSpec:
    process: str
    operation: str
    struct: str
    fields: list[InputField]
    output: Type
    run_status: str
    run_reason: str
    source: str
    existing_struct: str

    @property
    def input_cpp(self) -> str:
        return cpp_type_of_input(self.struct)

    @property
    def output_cpp(self) -> str:
        return cpp_type(self.output)

    @property
    def input_type_id(self) -> str:
        if self.struct == "CalibrateInput":
            return "acsd.input.Calibrate"
        return f"acsd.input.{self.struct}"

    @property
    def output_type_id(self) -> str:
        return type_id_schema(self.output)

    @property
    def bounds(self) -> tuple[int, int, str]:
        from .bindings import _BOUNDS_DEFAULT, PROCESS_BOUNDS
        return PROCESS_BOUNDS.get(self.process, _BOUNDS_DEFAULT)

    @property
    def hook_name(self) -> str:
        return self.operation.replace(".", "_")

    @property
    def add_function(self) -> str:
        return "add_operations_" + self.process.replace(".", "_")


def cpp_type_of_input(struct: str) -> str:
    return f"acsd::modules::{struct}"


def derive_specs(model: DeclarationModel) -> list[OpSpec]:
    specs: list[OpSpec] = []
    for binding in _binding_order():
        fields, output = derive_input(binding, model)
        if binding.existing_struct:
            _verify_existing_struct(binding, fields, model)
        specs.append(OpSpec(
            process=binding.process, operation=binding.operation,
            struct=binding.struct, fields=fields, output=output,
            run_status=binding.run_status,
            run_reason=binding.run_reason or _default_run_reason(binding),
            source=_source_signature(binding, model),
            existing_struct=binding.existing_struct))
    return specs


def _binding_order() -> list[OpBinding]:
    from . import bindings
    return bindings.OPERATIONS


def _default_run_reason(binding: OpBinding) -> str:
    return (
        f"not integrated before M5: the {binding.process} run hook must call "
        f"the single existing implementation through the runtime "
        f"model-context bridge (M4/M5). M0 registers the typed binding, "
        f"schema, codec and conservative bounds; no mock value is returned")


def _source_signature(binding: OpBinding, model: DeclarationModel) -> str:
    if binding.kind in ("free", "coadd"):
        candidates = model.functions.get(binding.declaration, [])
        if binding.discriminator:
            candidates = [candidate for candidate in candidates
                          if any(binding.discriminator in param[1]
                                 for param in candidate.params)]
        function = candidates[0]
        return f"{function.return_type} {binding.declaration}(...)"
    record = model.record(binding.interface)
    method = next(method for method in record.methods
                  if method.name == binding.declaration)
    return f"{method.return_type} {binding.interface}::{binding.declaration}(...)"


def _verify_existing_struct(binding: OpBinding, fields: list[InputField],
                            model: DeclarationModel) -> None:
    # The struct already declared in a module header must have exactly the
    # derived field list; otherwise the single declaration has drifted.
    text = Path(binding.existing_struct).read_text(encoding="utf-8")
    match = re.search(r"struct\s+" + re.escape(binding.struct) + r"\s*\{(.*?)\};",
                      text, re.S)
    if not match:
        raise SystemExit(
            f"{binding.existing_struct}: struct {binding.struct} not found")
    body = match.group(1)
    found = [(name, " ".join(type_.split()))
             for type_, name in re.findall(
                 r"([A-Za-z_][\w:<>,\s]*?)\s+([A-Za-z_]\w*)\s*;", body)]
    expected = [(field.name, field.cpp_type) for field in fields]
    normalized = [(name, type_)
                  for type_, name in sorted(
                      [(type_, name) for name, type_ in found])]
    expected_sorted = sorted((name, type_) for name, type_ in expected)
    if sorted(normalized) != expected_sorted:
        raise SystemExit(
            f"{binding.existing_struct}: {binding.struct} fields "
            f"{normalized} do not match the generated fields "
            f"{expected_sorted}")


