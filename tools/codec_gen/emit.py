def unique_outputs(specs: list[OpSpec]) -> list[Type]:
    seen: dict[str, Type] = {}
    for spec in specs:
        key = type_id_schema(spec.output)
        existing = seen.get(key)
        if existing is None:
            seen[key] = spec.output
        elif cpp_type(existing) != cpp_type(spec.output):
            raise SystemExit(
                f"TypeId '{key}' is bound to two C++ types "
                f"'{cpp_type(existing)}' and '{cpp_type(spec.output)}'")
    return list(seen.values())


