FROZEN_TABLE_B = {f.key: f for f in (
    # P4
    P4_NODE_REPRO_ABS, P4_FIT_NODE_REPRO_MIN_REL, P4_OPERATOR_SEP_MIN_REL,
    P4_CORNER_CONVENTION_MIN_REL, P4_MESH_MEDIAN_HELP_RATIO,
    P4_MESH_MEDIAN_HARM_RATIO, P4_KAPPA_MC_CI95_REL, P4_KAPPA_GAP_MIN_N5,
    P4_KAPPA_TABLE,
    # P5
    P5_SEAM_GATE, P5_SEAM_STEP_CRIT_REL, P5_REL_STEP_CLOSED_REL,
    P5_RAMP_CLOSED_REL, P5_DSCAN_RATIO, P5_DHAT_RAMP_ABS,
    P5_SIGMA_SEAM_ANALYTIC_OVER_MIN, P5_SKY_BILINEAR_ERR_REL,
    P5_KCORR_SCALING_RTOL, P5_ZERO_SCALE_FRAC, P5_HUBER_DELTA,
)}


def get(key: str) -> Frozen:
    """按 key 取 P4/P5 新增冻结容差。未知 key 抛错——**不许在用例里现编容差**。"""
    try:
        return FROZEN_TABLE_B[key]
    except KeyError:
        raise KeyError(
            f"未冻结的 P4/P5 容差 key={key!r}；先在 eng/tests/synthetic/_tol_chain_b.py "
            f"登记值、适用量级域与来源（不得改 tolerances.py）"
        ) from None


def value(key: str):
    """取冻结值本身（dict / callable 的条目照原样返回，由用例按 `note` 的口径解释）。"""
    return get(key).value


if __name__ == "__main__":  # pragma: no cover - 人工查阅入口
    print("=" * 78)
    print("P4 / P5 合成全链不变量 —— 新增冻结容差表（_tol_chain_b.py）")
    print("=" * 78)
    print(f"通用档只引用不改写：f64 rtol={F64_RTOL}  z95={Z95}")
    print()
    for _k, _f in FROZEN_TABLE_B.items():
        print(f"{_k:44s} = {_f.value!r}")
        print(f"    域: {_f.scale_domain}")
        print(f"    源: {_f.source}")
        if _f.note:
            print(f"    注: {_f.note}")
        print()
    print(f"共 {len(FROZEN_TABLE_B)} 条；本表不含任何 0.0 值条"
          f"（P4/P5 的构造级恒等走 harness.exact 的位精确档，不占数值条）。")
    print()
    # 推导自检：把每条「科学推导」的闭式当场复算一遍，推导与字面常量脱钩即暴露。
    # (key, 闭式值, 关系) —— 关系 = "frozen>=derived" 表示冻结值比推导宽（只放宽不收紧），
    # "frozen<=derived" 表示冻结值比推导严（如 N=5 间隙、零尺度触发占比）。
    _checks = (
        (P5_SEAM_STEP_CRIT_REL, P5_SEAM_GATE.value / (1.0 - P5_SEAM_GATE.value / 2.0), ">="),
        (P5_RAMP_CLOSED_REL, (2.0 * 5.0e-3) ** 2 / 3.0, ">="),
        (P4_KAPPA_MC_CI95_REL, Z95 * math.sqrt(2.0 / (4000 - 1)), "~="),
        (P4_KAPPA_GAP_MIN_N5, (math.pi / 2 - P4_KAPPA_TABLE.value[5]) / (math.pi / 2), "<="),
        (P5_SKY_BILINEAR_ERR_REL, 3.0e-2 / 4.0, ">="),
        (P5_DHAT_RAMP_ABS, 4 * 2 * 2.0e-2 * (2 * 5.0e-3) ** 2 / 3.0, ">="),
    )
    print("推导自检（闭式 vs 冻结字面量）:")
    for _f, _derived, _rel in _checks:
        _frozen = _f.value
        if _rel == ">=":
            _ok = _frozen >= _derived * (1.0 - 1e-12)
        elif _rel == "<=":
            _ok = _frozen <= _derived * (1.0 + 1e-12)
        else:  # "~=" : 冻结值就是推导值本身（不取整）
            _ok = abs(_frozen - _derived) <= 1e-12 * _derived
        print(f"  {_f.key:34s} 闭式={_derived:.10g}  冻结={_frozen:.10g} {_rel}  "
              f"{'✅' if _ok else '❌ 与推导脱钩'}")
    _thr = math.ceil(0.5 * 289) / 289.0
    print(f"  {P5_ZERO_SCALE_FRAC.key:34s} 闭式(整数触发阈 ⌈0.5×289⌉/289="
          f"{_thr:.10g})  冻结={P5_ZERO_SCALE_FRAC.value:.10g}  "
          f"= 正本「半数」逐字值 {'✅' if P5_ZERO_SCALE_FRAC.value == 0.5 else '❌'}")
