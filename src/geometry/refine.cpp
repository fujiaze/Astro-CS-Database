Result<Ref<GeometryRevision>> refine_geometry(Context& context, const RefinableGeometryProvider& provider,
                                              Ref<GeometrySnapshot> base, const GeometryBudget& request) {
  using model::fail;
  using model::ok_result;
  (void)provider;
  if (!base) {
    return fail<Ref<GeometryRevision>>(Code::missing_dependency, "missing_base_snapshot",
                                       "refine_geometry");
  }
  if (context.cancellation.requested()) {
    return fail<Ref<GeometryRevision>>(Code::cancelled, "cancelled", "refine_geometry");
  }

  auto next = std::make_shared<GeometrySnapshot>();
  next->functionals = base->functionals;
  next->dependents = base->dependents;
  next->recipes = base->recipes;

  std::vector<SourceIdentity> affected_sources;
  std::vector<HealpixLeaf> affected_leaves;
  std::vector<Box> affected_domains;
  std::vector<Id> affected_constraints;
  std::vector<Replacement> replacements;
  GeometryStatus status;
  status.termination = Termination::tolerance_met;
  status.bound_validity = Validity::certified;
  status.support = SupportState::positive;

  for (std::size_t index = 0; index < base->overlaps.size(); ++index) {
    const Ref<Overlaps>& old_overlaps = base->overlaps[index];
    if (!old_overlaps || !old_overlaps->recipe) continue;
    const GeometryRecipe& recipe = *old_overlaps->recipe;
    if (!recipe.footprints || !recipe.footprints->wcs) {
      return fail<Ref<GeometryRevision>>(Code::missing_dependency, "recipe_without_footprints",
                                         "refine_geometry");
    }
    Result<Ref<FootprintProvider>> footprint_provider =
        acsd::make_footprint_provider(context, recipe.footprints->wcs);
    if (!ok(footprint_provider)) {
      return fail<Ref<GeometryRevision>>(footprint_provider.code, "provider_unavailable",
                                         "refine_geometry");
    }
    // The refinement keeps the same identity but recomputes the overlap with
    // the requested budget; the primitive table is regenerated by the kernel.
    Ref<DetectorFootprint> footprint;
    Result<std::vector<U64>> source_rows = read_source_rows(context, recipe.source_rows);
    if (!ok(source_rows)) {
      return fail<Ref<GeometryRevision>>(source_rows.code, "recipe_source_rows_unavailable",
                                         "refine_geometry");
    }
    if (val(source_rows).empty()) continue;
    const U64 row = val(source_rows).front();
    Result<Ref<DetectorFootprint>> detector =
        detector_footprint(context, recipe.footprints, row);
    if (!ok(detector)) {
      return fail<Ref<GeometryRevision>>(detector.code, "detector_footprint_unavailable",
                                         "refine_geometry");
    }
    footprint = val(detector);
    Result<Ref<Overlaps>> refreshed = compute_overlap(context, *val(footprint_provider), footprint,
                                                       recipe.order, recipe.pixfrac, request);
    if (!ok(refreshed)) {
      // A refinement that cannot be computed keeps the previous bounds and
      // reports the failure; the old snapshot stays readable.
      status.termination = Termination::unsupported;
      status.support = SupportState::bounded_undecided;
      next->overlaps.push_back(old_overlaps);
      continue;
    }
    const Ref<Overlaps>& new_overlaps = val(refreshed);
    next->overlaps.push_back(new_overlaps);
    affected_sources.push_back(footprint->source);
    for (const OverlapContribution& contribution : new_overlaps->contributions) {
      affected_leaves.push_back(contribution.leaf);
      affected_constraints.push_back(contribution.shared_geometry_constraints);
    }
    if (new_overlaps->primitives) {
      affected_constraints.push_back(new_overlaps->primitives->identity.object_id);
    }
    if (new_overlaps->constraints) {
      affected_constraints.push_back(new_overlaps->constraints->identity.object_id);
    }
    Replacement replacement;
    replacement.old_hash = old_overlaps->identity.object_id;
    replacement.new_hash = new_overlaps->identity.object_id;
    replacements.push_back(replacement);
    if (new_overlaps->status.termination != Termination::tolerance_met) {
      status.termination = new_overlaps->status.termination;
      status.support = SupportState::bounded_undecided;
    }
  }

  // The operators are rebuilt from the same recipes and the same source values.
  for (std::size_t index = 0; index < next->overlaps.size() && index < base->source_inputs.size();
       ++index) {
    DrizzleRequest drizzle;
    if (next->overlaps[index] && next->overlaps[index]->recipe) {
      drizzle.order = next->overlaps[index]->recipe->order;
      drizzle.pixfrac = next->overlaps[index]->recipe->pixfrac;
    }
    drizzle.budget = request;
    Result<DrizzleResult> operator_result =
        build_drizzle(context, next->overlaps[index], base->source_inputs[index], drizzle);
    if (ok(operator_result)) {
      next->operators.push_back(val(operator_result).op);
    }
  }

  next->identity = model::make_identity("acsd.GeometrySnapshot", 2, 0,
                                        model::sha256_hex("acsd.geometry.snapshot"), "acsd");
  next->assessment = model::make_assessment(Code::ok);
  next->assessment.complete = status.termination == Termination::tolerance_met;
  next->assessment.science = status.termination == Termination::tolerance_met
                                 ? ScienceState::bounded
                                 : ScienceState::unconverged;

  auto revision = std::make_shared<GeometryRevision>();
  revision->base = base;
  revision->next = next;
  revision->affected_sources = affected_sources;
  revision->affected_leaves = affected_leaves;
  revision->affected_domains = affected_domains;
  revision->affected_constraints = affected_constraints;
  revision->replacements = replacements;
  revision->consumed = context.resources.usage();
  revision->status = status;
  revision->identity = model::make_identity("acsd.GeometryRevision", 2, 0,
                                            model::sha256_hex("acsd.geometry.revision"), "acsd");
  revision->assessment = model::make_assessment(Code::ok);
  revision->assessment.complete = status.termination == Termination::tolerance_met;
  revision->assessment.science = status.termination == Termination::tolerance_met
                                     ? ScienceState::bounded
                                     : ScienceState::unconverged;
  model::set_included(revision->assessment, "immutable_previous_snapshot");
  model::set_included(revision->assessment, "replacement_closure");
  return ok_result(std::static_pointer_cast<const GeometryRevision>(revision));
}

