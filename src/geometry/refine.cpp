Result<std::vector<U64>> read_source_rows(Context& context, ArrayRef array) {
  const U64 count = array->shape.empty() ? 0 : array->shape[0];
  Result<ArrayView> view = context.storage.read(context, array, BlockRequest{0, count});
  if (!ok(view)) {
    return model::fail<std::vector<U64>>(view.code, "source_rows_read_failed", "read_source_rows");
  }
  return model::ok_result(model::decode_u64(val(view).bytes));
}

